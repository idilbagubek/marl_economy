"""Run-directory tidy-up helpers.

Every artifact we produce (CSV logs, JSON snapshots, plots, checkpoints)
lives inside a run directory like `runs/<kind>_<regime>_<stage>_<seed>_<ts>/`.
This module writes a human-readable `README.md` at the top of that
directory and a companion `INFO.md` next to the plots to identify
which run produced any given file even after files are moved out of
their original run directory.
"""

from __future__ import annotations

import json
import os
from datetime import datetime
from pathlib import Path
from typing import Optional


# ---------------------------------------------------------------------------
# Run label - short string identifying the run (used in plot titles / file
# prefixes / printed banners).
# ---------------------------------------------------------------------------


def run_label(config: dict) -> str:
    """Compact run identifier: 'LME | stage 1 | seed 0 | 2026-05-14 13:47'.

    Falls back gracefully when config fields are missing.
    """
    regime = config.get("regime") or config.get("regime_name") or "?"
    stage = config.get("curriculum_phase") or config.get("stage") or "?"
    seed = config.get("seed", "?")
    ts = config.get("timestamp") or datetime.now().strftime("%Y-%m-%d %H:%M")
    return f"{regime} | stage {stage} | seed {seed} | {ts}"


def short_run_id(config: dict) -> str:
    """Filesystem-safe short identifier for filename prefixing: 'LME_s1_seed0'."""
    regime = config.get("regime") or config.get("regime_name") or "regime"
    stage = config.get("curriculum_phase") or config.get("stage") or 0
    seed = config.get("seed", 0)
    return f"{regime}_s{stage}_seed{seed}"


# ---------------------------------------------------------------------------
# README writers.
# ---------------------------------------------------------------------------


_README_TEMPLATE = """# {kind_title}: {run_id}

**Generated**: {generated_at}

## Run configuration

| Field | Value |
|---|---|
{config_rows}

## Files in this directory

{files_section}

## Notes

- This README is auto-generated by `marl_economy.eval.run_metadata.write_run_readme`.
- The run is identified by `{regime}_s{stage}_seed{seed}` plus the timestamp in the directory name.
- For Unity playback, run:
  ```
  python -m marl_economy.viz.export_unity "{run_dir}"
  ```
- To regenerate plots from the CSV:
  ```
  python -m marl_economy.eval.plot_run "{run_dir}"
  ```
"""


def _format_config_rows(config: dict) -> str:
    """Render config dict as a markdown table body."""
    rows = []
    priority_keys = [
        ("regime", "Regime"),
        ("curriculum_phase", "Curriculum stage"),
        ("stage", "Stage"),
        ("seed", "Seed"),
        ("num_households", "Households"),
        ("num_firms", "Firms (init)"),
        ("num_firms_init", "Firms (init)"),
        ("episode_weeks", "Episode weeks"),
        ("warmup_weeks", "Warmup weeks"),
        ("num_iterations", "Iterations"),
        ("trainable", "Policies trained"),
        ("load_from", "Loaded from checkpoint"),
        ("base_lr", "Base LR"),
        ("compressed_quarterly", "Compressed quarterly?"),
        ("batched_k", "Batched K"),
    ]
    seen = set()
    for key, label in priority_keys:
        if key in config and config[key] is not None and key not in seen:
            rows.append(f"| {label} | `{config[key]}` |")
            seen.add(key)
    return "\n".join(rows) if rows else "| _no config fields available_ | |"


def _scan_files(run_dir: Path) -> str:
    """Produce a markdown list of files + brief descriptions of common ones."""
    descriptions = {
        "config.json": "Full run configuration (JSON).",
        "metrics_step.csv": "Per-week metrics, 80+ columns. Opens directly in Excel.",
        "summary.json": "Episode-level totals (deaths, events, final reward, etc.).",
        "snapshots.json": "Per-step world state for Unity / pygame playback.",
        "unity_playback.json": "Bundled Unity-friendly export (snapshots + metrics + summary).",
        "debug.log": "Internal debug messages from the run.",
        "README.md": "(this file) - auto-generated run summary.",
        "plots": "Subdirectory with PNG plots (run `plot_run` to (re)generate).",
        "best": "Best-reward RLlib checkpoint so far.",
        "final": "Final-iteration RLlib checkpoint.",
    }
    lines = []
    try:
        entries = sorted(os.listdir(run_dir))
    except FileNotFoundError:
        return "_run directory not yet populated_"
    for entry in entries:
        path = run_dir / entry
        kind = "dir" if path.is_dir() else "file"
        desc = descriptions.get(entry)
        # Iteration checkpoints (iter_N/) get a generic note.
        if desc is None and entry.startswith("iter_"):
            desc = f"RLlib checkpoint at iteration {entry[len('iter_'):]}."
        if kind == "dir":
            lines.append(f"- `{entry}/` - {desc or '(directory)'}")
        else:
            try:
                size = path.stat().st_size
                size_str = (
                    f"{size:,} bytes" if size < 1024
                    else f"{size / 1024:.1f} KB" if size < 1024 ** 2
                    else f"{size / 1024 ** 2:.1f} MB"
                )
            except OSError:
                size_str = "?"
            lines.append(f"- `{entry}` ({size_str}) - {desc or '(file)'}")
    return "\n".join(lines)


def write_run_readme(
    run_dir: str | Path,
    config: dict,
    kind: str = "Episode",
    extra_sections: Optional[dict] = None,
) -> str:
    """Write `README.md` summarizing the run.

    Args:
        run_dir: Directory to write into.
        config: Configuration dict (will be rendered as a markdown table).
        kind: Human-readable category ("Episode", "RLlib Training", "Evaluation").
        extra_sections: Optional dict of {section_title: section_body} to append.

    Returns:
        The README path as a string.
    """
    run_dir = Path(run_dir)
    run_dir.mkdir(parents=True, exist_ok=True)

    generated_at = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    regime = config.get("regime", "?")
    stage = config.get("curriculum_phase") or config.get("stage", "?")
    seed = config.get("seed", "?")

    body = _README_TEMPLATE.format(
        kind_title=kind,
        run_id=short_run_id(config),
        generated_at=generated_at,
        config_rows=_format_config_rows(config),
        files_section=_scan_files(run_dir),
        regime=regime,
        stage=stage,
        seed=seed,
        run_dir=str(run_dir).replace("\\", "/"),
    )

    if extra_sections:
        body += "\n"
        for title, content in extra_sections.items():
            body += f"\n## {title}\n\n{content}\n"

    readme_path = run_dir / "README.md"
    readme_path.write_text(body, encoding="utf-8")
    return str(readme_path)


def write_plots_info(plots_dir: str | Path, config: dict) -> str:
    """Write `INFO.md` inside the plots subdirectory so plot files can be
    traced back to their run even if copied elsewhere.
    """
    plots_dir = Path(plots_dir)
    plots_dir.mkdir(parents=True, exist_ok=True)
    label = run_label(config)
    body = (
        f"# Plots: {short_run_id(config)}\n\n"
        f"**{label}**\n\n"
        f"Generated: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n\n"
        f"All `.png` files in this directory are visualizations from the run\n"
        f"identified above. See the parent directory's `README.md` for the\n"
        f"full config + file index.\n"
    )
    info_path = plots_dir / "INFO.md"
    info_path.write_text(body, encoding="utf-8")
    return str(info_path)


def load_run_config(run_dir: str | Path) -> dict:
    """Load `config.json` from a run dir; return empty dict if missing."""
    run_dir = Path(run_dir)
    cfg_path = run_dir / "config.json"
    if not cfg_path.exists():
        return {}
    try:
        with cfg_path.open("r", encoding="utf-8") as f:
            return json.load(f)
    except Exception:
        return {}
